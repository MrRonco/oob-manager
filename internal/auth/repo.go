package auth

import (
	"context"
	"errors"
	"time"

	"oob-manager/internal/authz"
)

// Repository errors. Implementations must return (or wrap) these exact values.
var (
	ErrNotFound   = errors.New("auth: not found")
	ErrUsersExist = errors.New("auth: users already exist")
)

// User is a local account. Value type: repositories return copies.
type User struct {
	ID            string // 128-bit random, hex; generated by this package
	Username      string
	Role          authz.Role
	PasswordHash  string // PHC-format argon2id string
	TOTPSecretEnc []byte // TOTP secret sealed with Sealer, AAD = user ID
	TOTPConfirmed bool   // false until the user proves the authenticator works
	TOTPLastStep  int64  // last accepted TOTP time step (replay protection)
	Disabled      bool
	CreatedAt     time.Time
}

// UserRepo stores users.
type UserRepo interface {
	// CreateFirst inserts u only if no user exists yet, atomically; otherwise it returns
	// ErrUsersExist. It backs the first-admin bootstrap.
	CreateFirst(ctx context.Context, u User) error
	// GetByUsername returns ErrNotFound when absent. Usernames are matched exactly.
	GetByUsername(ctx context.Context, username string) (User, error)
	// GetByID returns ErrNotFound when absent.
	GetByID(ctx context.Context, id string) (User, error)
	// SetPasswordHash replaces the stored hash (used to upgrade argon2 parameters).
	SetPasswordHash(ctx context.Context, id, hash string) error
	// SetTOTP stores a sealed secret and its confirmed flag. TOTPLastStep is left
	// unchanged: steps are wall-clock based, so keeping it only rejects codes from the
	// past, and resetting it would let the confirmation code be replayed.
	SetTOTP(ctx context.Context, id string, secretEnc []byte, confirmed bool) error
	// ReEnrollTOTP stores a freshly generated sealed secret, clears TOTPConfirmed and
	// resets TOTPLastStep to 0 (a re-enrollment). Resetting the step is safe here, unlike
	// in SetTOTP: no code of the new secret has ever been accepted, and confirming it
	// records its step again.
	ReEnrollTOTP(ctx context.Context, id string, secretEnc []byte) error
	// AdvanceTOTPStep atomically sets TOTPLastStep = step only if step > TOTPLastStep and
	// reports whether it did. This compare-and-set is what makes codes single-use even
	// under concurrent requests.
	AdvanceTOTPStep(ctx context.Context, id string, step int64) (bool, error)
}

// Level is how far a session got through login.
type Level int

// Session levels.
const (
	LevelPending Level = iota + 1 // password verified, TOTP outstanding; not usable
	LevelFull                     // password + TOTP; usable
)

// Session is a server-side session. Only the SHA-256 of the cookie value is stored.
type Session struct {
	IDHash    []byte
	UserID    string
	Level     Level
	CreatedAt time.Time // absolute lifetime starts here; kept across rotations
	LastSeen  time.Time
	StepUpAt  time.Time // last successful TOTP (login or step-up); zero if none
	IP        string
	UserAgent string
}

// SessionRepo stores sessions keyed by IDHash.
type SessionRepo interface {
	Create(ctx context.Context, s Session) error
	// Get returns ErrNotFound when absent.
	Get(ctx context.Context, idHash []byte) (Session, error)
	// Touch updates LastSeen.
	Touch(ctx context.Context, idHash []byte, at time.Time) error
	// Replace atomically deletes oldIDHash and inserts s (session rotation). It returns
	// ErrNotFound if oldIDHash no longer exists, so a rotation cannot resurrect a
	// session that was logged out concurrently.
	Replace(ctx context.Context, oldIDHash []byte, s Session) error
	// Delete is a no-op when absent.
	Delete(ctx context.Context, idHash []byte) error
	// DeleteForUser removes every session of a user.
	DeleteForUser(ctx context.Context, userID string) error
}

// LockoutState is the failure counter for one key ("acct:<user>" or "ip:<addr>").
type LockoutState struct {
	Failures    int
	LastFailure time.Time
}

// LockoutRepo stores login failure counters. Keys are derived from attacker-supplied
// usernames, so implementations should prune rows whose LastFailure is older than the
// longest LockoutPolicy.ForgetAfter.
type LockoutRepo interface {
	// Get returns the zero state (and nil) when the key is absent.
	Get(ctx context.Context, key string) (LockoutState, error)
	// RecordFailure atomically increments Failures, sets LastFailure = at and returns
	// the new state.
	RecordFailure(ctx context.Context, key string, at time.Time) (LockoutState, error)
	// Reset deletes the key.
	Reset(ctx context.Context, key string) error
}

// Scope is an API token scope. Only ScopeRead exists, by design (PRD §2).
type Scope string

// ScopeRead is the only token scope.
const ScopeRead Scope = "read"

// APIToken is a machine credential. Only the SHA-256 of the token is stored.
type APIToken struct {
	ID         string
	Name       string
	Hash       []byte
	Scope      Scope
	CreatedBy  string // user ID
	CreatedAt  time.Time
	LastUsedAt time.Time // zero = never used
	RevokedAt  time.Time // zero = active
	ExpiresAt  time.Time // zero = never expires
}

// TokenRepo stores API tokens.
type TokenRepo interface {
	Create(ctx context.Context, t APIToken) error
	// GetByHash returns ErrNotFound when absent.
	GetByHash(ctx context.Context, hash []byte) (APIToken, error)
	// List returns every token (revoked and expired included), oldest first.
	List(ctx context.Context) ([]APIToken, error)
	MarkUsed(ctx context.Context, id string, at time.Time) error
	Revoke(ctx context.Context, id string, at time.Time) error
}
