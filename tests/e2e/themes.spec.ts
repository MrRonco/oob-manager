// Color themes and display preferences (settings slice S2): every palette in both
// schemes passes axe WCAG 2.2 AA on Overview, Server and Display preferences; the
// palette is server-rendered (checked with JavaScript off); the clock links to the preferences; an
// invalid time zone is refused and a user's own zone wins over the app default.
import { expect, test, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { loadState, signIn } from './auth';
import { readFileSync } from 'node:fs';
import * as path from 'node:path';

const palettes = ['graphite', 'high-contrast', 'solarized', 'nord', 'dracula', 'colorblind'] as const;
const schemes = ['dark', 'light'] as const;
const pages = [
  { name: 'overview', path: '/' },
  { name: 'server', path: '/servers/r730xd' },
  { name: 'display', path: '/preferences' },
];

async function axe(page: Page, label: string) {
  const r = await new AxeBuilder({ page })
    .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa', 'best-practice'])
    .analyze();
  const summary = r.violations.map((v) => `${v.id} (${v.impact}): ${v.nodes.length} node(s): ${v.help}`);
  expect(summary, `accessibility violations on ${label}`).toEqual([]);
}

async function savePrefs(page: Page, fields: { theme?: string; zone?: string }) {
  await page.goto('/preferences');
  if (fields.zone !== undefined) await page.locator('#p-zone').selectOption(fields.zone);
  if (fields.theme !== undefined) await page.locator(`input[name="theme"][value="${fields.theme}"]`).check();
  await page.getByRole('button', { name: 'Save preferences' }).click();
}

test('every theme in both schemes: axe on Overview, Server and Display', async ({ browser }) => {
  test.setTimeout(300_000);
  const st = await loadState();
  const ctx = await browser.newContext({ ignoreHTTPSErrors: true }); // axe itself needs JavaScript
  const page = await ctx.newPage();
  await signIn(page, st);
  for (const palette of palettes) {
    await savePrefs(page, { theme: palette });
    await expect(page.locator('html')).toHaveAttribute('data-palette', palette);
    for (const scheme of schemes) {
      await page.emulateMedia({ colorScheme: scheme });
      for (const p of pages) {
        const label = `${p.name} ${palette} ${scheme}`;
        await test.step(label, async () => {
          await page.goto(p.path);
          await expect(page.locator('html')).toHaveAttribute('data-palette', palette);
          await axe(page, label);
        });
      }
    }
  }
  await savePrefs(page, { theme: '' });
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'graphite');
  await ctx.close();
});

test('clock opens the preferences; own zone wins; an unknown zone is refused', async ({ browser }) => {
  const st = await loadState();
  const ctx = await browser.newContext({ ignoreHTTPSErrors: true, javaScriptEnabled: false });
  const page = await ctx.newPage();
  await signIn(page, st);
  await page.locator('a.clock-link').click();
  await expect(page.getByRole('heading', { name: 'Display preferences', level: 1 })).toBeVisible();

  // Without JavaScript the palette is still server-rendered.
  await savePrefs(page, { theme: 'nord' });
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'nord');
  await savePrefs(page, { theme: '' });
  await savePrefs(page, { zone: 'Asia/Tokyo' });
  await expect(page.getByText('Preferences saved.')).toBeVisible();
  await expect(page.locator('a.clock-link time')).toHaveText(/ JST$/);
  const iso = await page.locator('a.clock-link time').getAttribute('datetime');
  expect(iso, 'machine-readable time stays UTC').toMatch(/Z$/);

  // A tampered form value never reaches the database.
  const csrf = await page.locator('form[action="/preferences"] input[name="csrf_token"]').inputValue();
  const resp = await page.request.post('/preferences', { form: { csrf_token: csrf, time_zone: 'Mars/Olympus' } });
  expect(resp.status()).toBe(422);
  await page.goto('/');
  await expect(page.locator('a.clock-link time')).toHaveText(/ JST$/);

  await savePrefs(page, { zone: '' });
  await expect(page.locator('a.clock-link time')).toHaveText(/ UTC$/);
  await ctx.close();
});

// The palettes are OKLCH primitives behind light-dark() (generated by tools/themegen).
// The Go test resolves every semantic token to testdata/theme-hex.txt; this checks what
// Chromium actually paints: the page and every Display swatch (its own data-palette
// re-resolves the semantic layer) against that file, with the mode from the OS and from
// the app's own Theme switch (data-theme), which must win over the OS.
const golden = readFileSync(path.resolve(__dirname, '../../internal/web/ui/testdata/theme-hex.txt'), 'utf8')
  .split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split(' '));
const want = (palette: string, mode: string, token: string) =>
  golden.find(([p, m, t]) => p === palette && m === mode && t === token)?.[3];

type Prop = 'backgroundColor' | 'color' | 'borderTopColor' | 'borderBottomColor' | 'outlineColor';

// painted reads a computed colour back through a canvas as 8-bit sRGB. A colour that is
// not fully opaque (transparent, or an invalid value falling back to it) is reported as
// "alpha=N" instead of a hex that could pass for black.
async function painted(page: Page, selector: string, prop: Prop): Promise<string> {
  return page.locator(selector).first().evaluate((el, p) => {
    const ctx = document.createElement('canvas').getContext('2d')!;
    ctx.fillStyle = getComputedStyle(el)[p];
    ctx.fillRect(0, 0, 1, 1);
    const [r, g, b, a] = ctx.getImageData(0, 0, 1, 1).data;
    return a !== 255 ? `alpha=${a}` : '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');
  }, prop);
}

// One sample per semantic token the swatch draws (selector, property, token): fill weight
// (OK quiet with a mark, warning tinted with an outline, critical a solid fill).
const samples: [string, Prop, string][] = [
  ['', 'backgroundColor', 'bg'], ['', 'color', 'text'], ['', 'borderTopColor', 'border'],
  ['.sw-row', 'backgroundColor', 'surface'], ['.sw-row', 'borderBottomColor', 'border'],
  ['.sw-field', 'backgroundColor', 'surface-2'], ['.sw-field', 'color', 'muted'], ['.sw-field', 'borderTopColor', 'field-border'],
  ['.sw-link', 'color', 'accent'], ['.btn:not(.btn-secondary)', 'backgroundColor', 'btn-bg'],
  ['.btn:not(.btn-secondary)', 'color', 'btn-fg'], ['.sw-focus', 'outlineColor', 'focus'],
  ['.b-ok', 'color', 'text'], ['.b-ok .ic', 'color', 'ok-mark'], ['.b-warn', 'color', 'warn'],
  ['.b-warn', 'backgroundColor', 'warn-bg'], ['.b-warn', 'borderTopColor', 'warn-mark'], ['.b-crit', 'color', 'on-danger'],
  ['.b-crit', 'backgroundColor', 'danger'], ['.b-stale', 'color', 'stale-fg'], ['.b-stale', 'backgroundColor', 'stale-bg'],
  ['.b-stale', 'borderTopColor', 'stale-mark'], ['.r-warn', 'backgroundColor', 'warn-bg'],
];

async function expectPalettes(page: Page, mode: string, how: string) {
  await page.goto('/preferences');
  expect(await painted(page, 'body', 'backgroundColor'), `page bg, ${how}`).toBe(want('graphite', mode, 'bg'));
  expect(await painted(page, 'body', 'color'), `page text, ${how}`).toBe(want('graphite', mode, 'text'));
  for (const palette of palettes) {
    for (const [sel, prop, token] of samples) {
      const got = await painted(page, `.swatch[data-palette="${palette}"] ${sel}`.trimEnd(), prop);
      expect(got, `${palette} --${token} (${sel || 'swatch'} ${prop}), ${how}`).toBe(want(palette, mode, token));
    }
  }
}

// setTheme clicks the account menu's Theme switch (a server-rendered form) until <html>
// carries the wanted data-theme ('' = follow the OS).
async function setTheme(page: Page, theme: '' | 'dark' | 'light') {
  for (let i = 0; i < 4; i++) {
    await page.goto('/preferences');
    if (((await page.locator('html').getAttribute('data-theme')) ?? '') === theme) return;
    await page.locator('details.usermenu summary').click();
    await page.locator('details.usermenu').getByRole('button', { name: /^Theme:/ }).click();
  }
  throw new Error(`could not switch the theme to "${theme}"`);
}

test('painted colours equal the generated palette values, by OS scheme and by the Theme switch', async ({ browser }) => {
  test.setTimeout(240_000);
  const st = await loadState();
  const ctx = await browser.newContext({ ignoreHTTPSErrors: true });
  const page = await ctx.newPage();
  await signIn(page, st);
  await setTheme(page, '');
  for (const scheme of schemes) {
    await page.emulateMedia({ colorScheme: scheme });
    await expectPalettes(page, scheme, `OS ${scheme}`);
  }
  // data-theme overrides the OS in both directions.
  await page.emulateMedia({ colorScheme: 'dark' });
  await setTheme(page, 'light');
  await expectPalettes(page, 'light', 'data-theme=light under an OS dark scheme');
  await page.emulateMedia({ colorScheme: 'light' });
  await setTheme(page, 'dark');
  await expectPalettes(page, 'dark', 'data-theme=dark under an OS light scheme');
  await setTheme(page, '');
  await ctx.close();
});
